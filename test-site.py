from playwright.sync_api import sync_playwright, expect

with sync_playwright() as p:
    browser = p.chromium.launch(headless=True, executable_path='/usr/bin/google-chrome', args=['--no-sandbox'])
    page = browser.new_page(viewport={'width':1440,'height':1000})
    page.emulate_media(reduced_motion='reduce')
    errors = []
    page.on('pageerror', lambda error: errors.append(str(error)))
    page.goto('http://localhost:4200')
    expect(page.locator('.memory-card')).to_have_count(6)
    page.get_by_role('button', name='Adicionar memória', exact=True).click()
    page.get_by_label('Título', exact=True).fill('Nossa memória de teste')
    page.get_by_label('Data', exact=True).fill('2026-11-11')
    page.get_by_label('A história por trás da foto', exact=True).fill('Uma história com acentos: coração, lembranças e carinho.')
    page.locator('input[type=file]').set_input_files('/home/user/history-ab/packages/web/public/images/coast.jpg')
    expect(page.get_by_role('button', name='Salvar memória')).to_be_enabled()
    page.get_by_role('button', name='Salvar memória').click()
    expect(page.locator('dialog')).to_have_count(0)
    expect(page.locator('.memory-card')).to_have_count(7)
    page.reload()
    expect(page.locator('.memory-card')).to_have_count(7)
    page.get_by_label('Buscar uma memória').fill('CORACAO')
    expect(page.locator('.memory-card')).to_have_count(1)
    page.locator('.memory-card').click()
    expect(page.locator('.detail-image')).to_have_attribute('src', __import__('re').compile('^data:image/jpeg'))
    page.get_by_role('button', name='Editar memória', exact=True).click()
    page.get_by_label('Título', exact=True).fill('Memória atualizada')
    page.get_by_label('Data', exact=True).fill('2023-02-14')
    page.locator('input[type=file]').set_input_files('/home/user/history-ab/packages/web/public/images/sunset.jpg')
    expect(page.get_by_role('button', name='Salvar memória')).to_be_enabled()
    page.get_by_role('button', name='Salvar memória').click()
    expect(page.locator('dialog')).to_have_count(0)
    page.get_by_label('Buscar uma memória').fill('')
    page.get_by_label('Filtrar por ano').select_option('2023')
    expect(page.locator('.memory-card')).to_have_count(1)
    page.get_by_role('button', name='Linha do tempo', exact=True).first.click()
    expect(page.locator('.timeline-card')).to_have_count(1)
    expect(page.locator('.timeline-year')).to_have_text('2023')
    page.get_by_label('Filtrar por ano').select_option('all')
    page.get_by_label('Ordenar memórias').select_option('oldest')
    expect(page.locator('.timeline-card').first).to_contain_text('Memória atualizada')
    page.locator('.timeline-card').first.click()
    page.get_by_role('button', name='Excluir', exact=True).click()
    expect(page.get_by_role('heading',name='Excluir esta memória?')).to_be_visible()
    page.get_by_role('button', name='Cancelar', exact=True).click()
    expect(page.locator('dialog').get_by_role('heading',name='Memória atualizada',exact=True)).to_be_visible()
    page.get_by_role('button', name='Excluir', exact=True).click()
    page.get_by_role('button', name='Excluir memória', exact=True).click()
    expect(page.locator('dialog')).to_have_count(0)
    expect(page.locator('.timeline-card')).to_have_count(6)
    page.reload()
    expect(page.locator('.memory-card')).to_have_count(6)
    page.get_by_role('button',name='Adicionar memória',exact=True).click()
    page.get_by_label('Título',exact=True).fill('Só palavras')
    page.get_by_label('Data',exact=True).fill('2026-11-11')
    page.get_by_role('button',name='Salvar memória').click()
    expect(page.locator('.memory-card')).to_have_count(7)
    page.get_by_role('button',name='Abrir memória: Só palavras',exact=True).click()
    expect(page.locator('.detail-no-image')).to_be_visible()
    page.keyboard.press('Escape')
    expect(page.locator('dialog')).to_have_count(0)
    page.set_viewport_size({'width':390,'height':844})
    assert not page.evaluate('document.documentElement.scrollWidth > innerWidth'), 'Mobile overflow'
    page.get_by_role('button',name='Adicionar memória',exact=True).click()
    expect(page.locator('dialog')).to_be_visible()
    assert not page.evaluate('document.querySelector("dialog").scrollWidth > document.querySelector("dialog").clientWidth'), 'Modal overflow'
    page.keyboard.press('Escape')
    expect(page.locator('dialog')).to_have_count(0)
    # Clean test context for screenshots; user previews start from the illustrative collection.
    page.evaluate('indexedDB.deleteDatabase("the-history-ab")')
    page.reload()
    expect(page.locator('.memory-card')).to_have_count(6)
    page.screenshot(path='/home/user/history-ab/mobile-check.png',full_page=True)
    page.set_viewport_size({'width':1440,'height':1080})
    page.screenshot(path='/home/user/history-ab/desktop-check.png',full_page=True)
    print('PASS: upload, create, persist, accent search, edit, replace image, year filter, timeline, chronological sort, delete confirmation, delete persistence, text-only memory, Escape, mobile and modal overflow.')
    print('JavaScript errors:', errors)
    assert errors == []
    browser.close()